"""Regenerate .github/workflows/release.yml from the target lists below.
Run: python scripts/gen-release-workflow.py   (edit the lists, not the yml)"""
from pathlib import Path

FABRIC = ["1.21.1", "1.21.2", "1.21.3", "1.21.4", "1.21.5", "1.21.6", "1.21.7", "1.21.8",
          "1.21.9", "1.21.10", "1.21.11", "26.1", "26.1.1", "26.1.2", "26.2", "26.3"]
NEOFORGE = ["1.21.1", "1.21.3", "1.21.4", "1.21.5", "1.21.8", "1.21.10", "1.21.11", "26.1.2", "26.2", "26.3"]
FORGE = ["1.21.1", "1.21.3", "1.21.4", "1.21.5", "1.21.6", "1.21.7", "1.21.8", "1.21.9", "1.21.10",
         "1.21.11", "26.1", "26.1.1", "26.1.2", "26.2", "26.3"]
PAPER_VERSIONS = ["1.21", "1.21.1", "1.21.2", "1.21.3", "1.21.4", "1.21.5", "1.21.6", "1.21.7",
                  "1.21.8", "1.21.9", "1.21.10", "1.21.11", "26.1", "26.1.1", "26.1.2", "26.2", "26.3"]

include = []
for mc in FABRIC:
    include.append(("fabric", mc, "fabric", mc))
for mc in NEOFORGE:
    include.append(("neoforge", mc, "neoforge", mc))
for mc in FORGE:
    include.append(("forge", mc, "forge", mc))
include.append(("paper", "-", "paper\\n          spigot", "\\n          ".join(PAPER_VERSIONS)))

rows = []
for platform, mc, loaders, games in include:
    rows.append(f'          - {{platform: {platform}, mc: "{mc}"}}')

Path(".github/workflows/release.yml").write_text(f"""# Generated by scripts/gen-release-workflow.py - do not edit by hand.
name: release
on:
  push:
    tags: ["v*"]
  workflow_dispatch:
jobs:
  publish:
    runs-on: ubuntu-latest
    strategy:
      fail-fast: false
      max-parallel: 6
      matrix:
        include:
{chr(10).join(rows)}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: |
            21
            25
      - uses: gradle/actions/setup-gradle@v4
      - name: Build
        id: build
        run: |
          out=$(scripts/build-target.sh ${{{{ matrix.platform }}}} ${{{{ matrix.mc }}}} | tee /dev/stderr | tail -1)
          echo "$out" >> "$GITHUB_OUTPUT"
      - name: Version info
        id: info
        run: |
          ver=$(grep '^modVersion' gradle.properties | cut -d= -f2 | tr -d ' \\r')
          echo "ver=$ver" >> "$GITHUB_OUTPUT"
          if [ "${{{{ matrix.platform }}}}" = paper ]; then
            echo "label=Paper plugin" >> "$GITHUB_OUTPUT"
            echo "loaders=paper,spigot" >> "$GITHUB_OUTPUT"
            echo "games={",".join(PAPER_VERSIONS)}" >> "$GITHUB_OUTPUT"
          else
            echo "label=${{{{ matrix.platform }}}} ${{{{ matrix.mc }}}}" >> "$GITHUB_OUTPUT"
            echo "loaders=${{{{ matrix.platform }}}}" >> "$GITHUB_OUTPUT"
            echo "games=${{{{ matrix.mc }}}}" >> "$GITHUB_OUTPUT"
          fi
      - name: Release notes
        run: scripts/release-notes.sh "${{{{ matrix.platform }}}}" "${{{{ matrix.mc }}}}" "${{{{ steps.info.outputs.ver }}}}" > release-notes.md
      - uses: Kir-Antipov/mc-publish@v3.3
        with:
          modrinth-id: v2ecfuiA
          modrinth-token: ${{{{ secrets.MODRINTH_TOKEN }}}}
          files: ${{{{ steps.build.outputs.JAR }}}}
          name: DMCL ${{{{ steps.info.outputs.ver }}}} (${{{{ steps.info.outputs.label }}}})
          version: ${{{{ steps.info.outputs.ver }}}}+${{{{ matrix.platform }}}}-${{{{ matrix.mc }}}}
          version-type: release
          loaders: ${{{{ steps.info.outputs.loaders }}}}
          game-versions: ${{{{ steps.info.outputs.games }}}}
          dependencies: |
            ${{{{ matrix.platform == 'fabric' && 'fabric-api(required){{modrinth:P7dR8mSH}}' || '' }}}}
          changelog-file: release-notes.md
""")
